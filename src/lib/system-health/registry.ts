/**
 * =============================================================
 * MONITORED ENDPOINT REGISTRY
 * =============================================================
 *
 * The single list of routes the scan probes, derived from the real
 * route handlers under `src/app/api`. Adding a monitored endpoint
 * means adding one entry here; no probe code changes.
 *
 * `expect` is what a correctly configured deployment must return to
 * an anonymous GET. Three kinds appear:
 *
 *   availability — a public surface that must serve traffic (200)
 *   protected    — must reject anonymous access (401/403)
 *   method-guard — must reject an unsupported verb (405)
 *
 * Every probe is a credential-free GET, so a mutating route is
 * verified precisely by its refusal.
 */

export type EndpointKind = "availability" | "protected" | "method-guard";

export interface MonitoredEndpoint {
  id: string;
  /** Operator-facing name. */
  label: string;
  path: string;
  kind: EndpointKind;
  /** Status codes that represent correct behaviour. */
  expect: number[];
  weight: number;
  /** What this endpoint does, shown beside the result. */
  purpose: string;
  /**
   * For `protected` endpoints, whether the guard is admin-level.
   * Drives the authorisation section rather than just authentication.
   */
  adminOnly?: boolean;
}

